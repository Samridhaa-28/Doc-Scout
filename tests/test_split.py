"""Dev/test split by document: no document in both splits, every question assigned once, deterministic."""
import json

from docscout.config import get_config
from eval.split import split_by_document, split_file


def test_split_has_no_document_overlap():
    docs = [f"doc{i}" for i in range(49)]
    qdocs = {f"q{i}": docs[i % 49] for i in range(293)}
    sp = split_by_document(docs, qdocs, 0.2, seed=42)
    assert not set(sp["dev"]["doc_ids"]) & set(sp["test"]["doc_ids"])
    assert len(sp["dev"]["doc_ids"]) == 10 and len(sp["test"]["doc_ids"]) == 39
    allq = sp["dev"]["question_ids"] + sp["test"]["question_ids"]
    assert sorted(allq) == sorted(qdocs) and len(set(allq)) == len(allq)
    for name in ("dev", "test"):
        assert all(qdocs[q] in set(sp[name]["doc_ids"]) for q in sp[name]["question_ids"])
    assert split_by_document(docs, qdocs, 0.2, seed=42) == sp


def test_saved_split_file_has_no_overlap():
    f = split_file(get_config())
    if not f.exists():
        return  # generated by `python -m eval.split`
    sp = json.loads(f.read_text(encoding="utf-8"))
    assert not set(sp["dev"]["doc_ids"]) & set(sp["test"]["doc_ids"])
    assert not set(sp["dev"]["question_ids"]) & set(sp["test"]["question_ids"])
